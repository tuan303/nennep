/** Icon component of a content icon name (unknown → BookOpen). */
export function guideIcon(name: GuideIcon | undefined): LucideIcon {
  return (name && Object.prototype.hasOwnProperty.call(GUIDE_ICONS, name) ? GUIDE_ICONS[name] : undefined) ?? BookOpen;
}
